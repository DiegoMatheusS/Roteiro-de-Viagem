import assert from 'node:assert/strict';
import fs from 'node:fs';
import sharp from 'sharp';
import {chromium} from 'playwright';
import {createServer} from 'vite';
import {openDatabase} from '../server/db';
import {createApi} from '../server/app';
import {importPublicAddress} from '../server/addressImport';

const db=openDatabase(':memory:');let external=0;
importPublicAddress(db,{id:'memory-ui',name:'Imóvel da memória do teste',street:'Rua da Memória',houseNumber:'100',postcode:'05555-111',city:'São Paulo',state:'SP',coords:[-23.54,-46.62]});
const api=createApi({db,mapFetch:(async()=>{external++;throw Error('API de terceiros não deve ser usada');}) as typeof fetch}).listen(3001,'127.0.0.1');
await new Promise<void>(resolve=>api.once('listening',resolve));
const vite=await createServer({server:{host:'127.0.0.1',port:3000,strictPort:true}});await vite.listen();
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH,args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'});
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));let requests=0;
  page.on('request',request=>{if(new URL(request.url()).pathname==='/api/addresses/search')requests++;});
  const tile=await sharp({create:{width:256,height:256,channels:4,background:'#e8f0ed'}}).png().toBuffer();
  await page.route(/^https:\/\//,route=>route.fulfill({contentType:'image/png',body:tile}));
  await page.goto('http://127.0.0.1:3000/tests/fixtures/address-memory.html');
  const query='Rua da Memória, 100, São Paulo';
  await page.getByRole('textbox',{name:'Origem',exact:true}).fill(query);
  await page.getByRole('button',{name:'Buscar origem',exact:true}).click();
  await page.getByRole('button',{name:/Imóvel da memória do teste/}).click();
  assert.equal(requests,1);
  await page.getByRole('textbox',{name:'Destino',exact:true}).fill(query);
  await page.getByRole('button',{name:'Buscar destino',exact:true}).click();
  await page.getByRole('button',{name:/Imóvel da memória do teste/}).click();
  assert.equal(requests,1,'origem e destino reutilizam o mesmo endereço guardado');
  await page.reload();await page.context().setOffline(true);
  await page.getByRole('textbox',{name:'Destino',exact:true}).fill(query);
  await page.getByRole('button',{name:'Buscar destino',exact:true}).click();
  await page.getByRole('button',{name:/Imóvel da memória do teste/}).click();
  let selected=JSON.parse((await page.getByTestId('destination').textContent())!);
  assert.deepEqual(selected.coords,[-23.54,-46.62]);assert.equal(selected.addressParts.postcode,'05555111');
  assert.equal(requests,1,'o endereço permanece disponível ao reabrir sem internet');
  await page.context().setOffline(false);
  const missing='Rua do Cadastro Novo, 321, São Paulo, SP';
  await page.getByRole('textbox',{name:'Destino',exact:true}).fill(missing);
  await page.getByRole('button',{name:'Buscar destino',exact:true}).click();
  await page.getByRole('button',{name:'Marcar endereço no mapa (sem número ou não encontrado)'}).click();
  const picker=page.getByRole('dialog',{name:'Marcar endereço no mapa'});
  const map=picker.getByTestId('manual-address-map');await map.locator('.leaflet-pane').first().waitFor({state:'attached'});
  const confirm=picker.getByRole('button',{name:'Confirmar local do pino'});
  assert.equal(await confirm.isDisabled(),true,'a referência inicial não confirma automaticamente o imóvel');
  const box=(await map.boundingBox())!;await page.mouse.click(box.x+box.width/2+34,box.y+box.height/2+18);
  await picker.getByRole('textbox',{name:'Número do imóvel',exact:true}).fill('321');
  await picker.getByRole('textbox',{name:'CEP do endereço',exact:true}).fill('05555-777');
  await confirm.click();
  selected=JSON.parse((await page.getByTestId('destination').textContent())!);
  assert.equal(selected.addressParts.houseNumber,'321');assert.equal(selected.addressParts.postcode,'05555777');
  const calls=requests;await page.context().setOffline(true);
  await page.getByRole('textbox',{name:'Origem',exact:true}).fill(missing);
  await page.getByRole('button',{name:'Buscar origem',exact:true}).click();
  await page.getByRole('button',{name:/Rua do Cadastro Novo, 321/}).click();
  const reused=JSON.parse((await page.getByTestId('origin').textContent())!);
  assert.deepEqual(reused.coords,selected.coords);assert.equal(reused.addressParts.postcode,'05555777');assert.equal(requests,calls);
  assert.equal(external,0);assert.deepEqual(errors,[]);
  fs.mkdirSync('test-results',{recursive:true});await page.screenshot({path:'test-results/address-memory.png'});
  console.log('PASS: API própria, origem/destino reutilizados após reabrir offline, endereço ausente marcado no mapa com número/CEP, zero consultas externas.');
}catch(error){for(const context of browser.contexts())for(const page of context.pages()){
  console.error((await page.locator('body').innerText()).slice(-4500));await page.screenshot({path:'test-results/address-memory-failure.png'}).catch(()=>{});
}throw error;}finally{await browser.close();await vite.close();await new Promise<void>(resolve=>api.close(()=>resolve()));db.close();}
